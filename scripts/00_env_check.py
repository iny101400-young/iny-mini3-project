# pandas 라이브러리를 pd라는 이름으로 불러온다
import pandas as pd

# 표에 넣을 가상 데이터를 사전 형태로 만든다
data = {
    # 첫 번째 열: 누가 봐도 가짜인 PDF AI 도구 이름 3개
    "PDF AI 도구": ["가짜PDF봇", "테스트문서AI", "예시요약기"],
    # 두 번째 열: 월 요금을 숫자(원 단위)로 넣는다
    "월 요금": [9900, 14900, 19900],
}

# 사전 데이터를 pandas 데이터프레임(표)으로 바꾼다
df = pd.DataFrame(data)

# 표 위에 안내 문구를 출력한다
print("환경 확인용 가상 예시")

# 만든 표를 출력한다
print(df)

# 표의 크기(행 수, 열 수)를 출력한다
print(df.shape)
